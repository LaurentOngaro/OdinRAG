# ─── HELPERS ─────────────────────────────────────────────────────────────────
def count_md_files(root: Path) -> tuple[int, int]:
    """Return (count, total size in bytes) for .md files under `root`."""
    if not root.exists():
        return 0, 0
    count = 0
    total = 0
    for p in root.rglob("*.md"):
        if p.is_file():
            count += 1
            try:
                total += p.stat().st_size
            except OSError:
                pass
    return count, total


def count_snapshot_files(root: Path) -> tuple[int, int]:
    """Count .txt snapshots + .md README under `root`.

    Used for `gitIngest/` which stores gitingest output as .txt files
    (not .md). Returns (count, total size in bytes) summed across both.
    """
    if not root.exists():
        return 0, 0
    count = 0
    total = 0
    for ext in ("*.md", "*.txt"):
        for p in root.rglob(ext):
            if p.is_file():
                count += 1
                try:
                    total += p.stat().st_size
                except OSError:
                    pass
    return count, total


def parse_karl_readme(readme: Path) -> list[dict]:
    """Parse `odin-book/README.md` to extract the chapter table.

    Returns:
        [{"number": "1", "title": "Introduction", "path": "01-introduction.md"}, ...]
    """
    if not readme.exists():
        return []
    text = readme.read_text(encoding="utf-8")
    chapters: list[dict] = []
    in_table = False
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("**Chapter ") or s.startswith("- **Chapter "):
            in_table = True
        if in_table:
            m = re.search(r"\*\*Chapter\s+(\d+)\*\*\s*[-–-]\s*\[([^\]]+)\]\(([^)]+)\)", s)
            if m:
                chapters.append({"number": m.group(1), "title": m.group(2), "path": m.group(3), })
            elif "**Appendix" in s:
                in_table = False
    return chapters


def parse_karl_appendices(out_dir: Path) -> list[dict]:
    """List appendix files from `odin-book/appendices/`."""
    appx_dir = out_dir / "odin-book" / "appendices"
    if not appx_dir.exists():
        return []
    appx = []
    for p in sorted(appx_dir.glob("*.md")):
        m = re.match(r"^([A-Z])-(.+)\.md$", p.name)
        if m:
            appx.append({"number": m.group(1), "title": m.group(2).replace("-", " ").title(), "path": f"appendices/{p.name}"})
    return appx


def extract_manual_section(text: str) -> str:
    """Return the content between MANUAL_START and MANUAL_END, or empty string."""
    m = _SECTION_RE.search(text)
    return m.group(1).strip("\n") if m else ""


def has_markers(text: str) -> bool:
    """True if the text already contains AUTO/MANUAL sentinels."""
    return AUTO_START in text and MANUAL_START in text


def format_markdown_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    """Format an aligned markdown table."""
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            if i < len(widths):
                widths[i] = max(widths[i], len(cell))
    header_line = "| " + " | ".join(h.ljust(widths[i]) for i, h in enumerate(headers)) + " |"
    separator_line = "| " + " | ".join("-" * widths[i] for i in range(len(headers))) + " |"
    table_lines = [header_line, separator_line]
    for row in rows:
        line = "| " + " | ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)) + " |"
        table_lines.append(line)
    return table_lines


